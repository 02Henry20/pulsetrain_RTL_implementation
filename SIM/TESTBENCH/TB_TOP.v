`timescale 1ns/100ps
`define PER 10

module TB_TOP_PREV();

	initial begin
	`ifdef sdf_gate
	 $sdf_annotate("TOP_PREV.sdf_PT", U_TOP_PREV);
	`endif
	
	`ifdef sdf_post_wst
	 $sdf_annotate("./TOP_PREV_max.sdf_PT",U_TOP_PREV);
	`endif
	
	`ifdef sdf_post_bst
	 $sdf_annotate("./TOP_PREV_min.sdf_PT", U_TOP_PREV);
	`endif
	end

	reg	[31:0]	DI;
	reg	[1:0]	ADDR;
	reg		WEN;
	wire	[31:0]	DO;
	
	reg		CLK;
	reg		RSTn;
	
	TOP_PREV U_TOP_PREV (
		.DI(DI),
		.ADDR(ADDR),
		.WEN(WEN),
		.DO(DO),

		.CLK(CLK),
		.RSTn(RSTn)
	);
	
	integer	i;

	wire		end_flag;

	assign		end_flag	=	(i == 1000) | (DO[1] == 1'b1);	
	
	initial begin
		CLK	=	1'b0;
		RSTn	=	1'b1;
		WEN	=	1'b1;
		ADDR	=	2'b00;
		DI	=	32'd0;
		
		#(10*`PER)
		RSTn	=	1'b0;
	
		#(10*`PER)
		RSTn	=	1'b1;

		#(10*`PER)

		// 2'b01 : instruction
		for (i = 0; i < 1024; i = i+1) begin
			#(`PER)
			ADDR	=	2'b01;
			WEN	=	1'b0;

			case (i)

				// core end test
//				100:		DI = {12'b111111111111, 5'b00000, 3'b000, 5'b00001, 7'b0010011};	// ADDI x1, x0, -1
//				101:		DI = {7'b0100000, 5'b00000, 5'b00001, 3'b000, 5'b00000, 7'b0110011};	// ADD x1, x0, x0
//				100:		DI = {20'b1000_0000_0000_0000_0000, 5'b00001, 7'b0110111};		// LUI x1, 0x800
//				101:		DI = {12'b0000_0000_0001, 5'b00001, 3'b000, 5'b00000, 7'b0010011};	// ADDI x0, x1, 0x1


				// vector load 32b (64-vector 8-stream)
//				0:		DI = {12'b0000_0100_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
//				1:		DI = {4'b0101, 8'b00000001, 5'b00001, 3'b000, 1'b0, 1'b1, 3'b111, 7'b0101011};


				// vector load 32b (32-vector 8-stream)
//				0:		DI = {12'b0000_0110_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
//				1:		DI = {4'b0101, 8'b00000001, 5'b00001, 3'b001, 1'b0, 1'b1, 3'b111, 7'b0101011};


				// vector load 32b (16-vector 8-stream)
//				0:		DI = {12'b0000_0100_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
//				1:		DI = {4'b0101, 8'b00000001, 5'b00001, 3'b010, 1'b0, 1'b1, 3'b111, 7'b0101011};	


				// vector load 32b (64-element 8-stream)
//				0:		DI = {12'b0000_0100_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};	
//				1:		DI = {4'b0101, 8'b0000_0001, 5'b00001, 3'b011, 1'b0, 1'b1, 3'b111, 7'b0101011};


				// (8x64)x(64x1) multiplication
//				0:		DI = {12'b1000_0000_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};  	
//				1:		DI = {4'b0100, 8'b1111_1111, 5'b00000, 3'b011, 3'b000, 2'b00, 7'b0001011};
//				2:		DI = {4'b0001, 8'b1111_1111, 5'b00001, 3'b000, 1'b0, 1'b0, 3'b000, 7'b0101011};
//				3:		DI = {12'b1000_0000_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
//				4:		DI = {4'b0100, 8'b0000_0001, 5'b00001, 3'b000, 1'b0, 1'b1, 3'b111, 7'b0101011};
//				5:		DI = {12'b0000_0100_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
//				6:		DI = {4'b0001, 8'b1111_1111, 5'b00001, 3'b100, 5'b00000, 7'b0101011};


				// (64x64)x(64x1) multiplication
 				0:		DI = {12'b0000_0000_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
 				1:		DI = {12'b0000_0100_0000, 5'b00000, 3'b000, 5'b00010, 7'b0010011};
 				2:		DI = {20'b0000_0000_0000_0000_0010, 5'b00011, 7'b0110111};
 				3:		DI = {12'b1111_1111_1000, 5'b00011, 3'b000, 5'b00011, 7'b0010011};
 				4:		DI = {12'b0000_0000_0000, 5'b00000, 3'b000, 5'b00100, 7'b0010011};
 				5:		DI = {12'b0000_0000_1000, 5'b00000, 3'b000, 5'b00101, 7'b0010011};
 				6:		DI = {4'b0001, 8'b1111_1111, 5'b00001, 3'b000, 1'b0, 1'b0, 3'b000, 7'b0101011};
 				7:		DI = {4'b0100, 8'b1111_1111, 5'b00000, 3'b111, 3'b000, 2'b00, 7'b0001011};
 				8:		DI = {4'b0100, 8'b0000_0001, 5'b00010, 3'b000, 1'b0, 1'b1, 3'b111, 7'b0101011};
 				9:		DI = {12'b0000_0000_0001, 5'b00100, 3'b000, 5'b00100, 7'b0010011};
 				10:		DI = {12'b0010_0000_0000, 5'b00010, 3'b000, 5'b00010, 7'b0010011};
 				11:		DI = {12'b0000_0000_1000, 5'b00011, 3'b000, 5'b00011, 7'b0010011};
 				12:		DI = {4'b0001, 8'b1111_1111, 5'b00011, 3'b100, 5'b00000, 7'b0101011};
 				13:		DI = {1'b1, 6'b11_1111, 5'b00100, 5'b00101, 3'b001, 4'b0110, 1'b1, 7'b1100011};
 				14:		DI = {12'b0000_0000_0000, 5'b00000, 3'b000, 5'b00000, 7'b0010011};
				15:		DI = {20'b1000_0000_0000_0000_0000, 5'b00001, 7'b0110111};
				16:		DI = {12'b0000_0000_0001, 5'b00001, 3'b000, 5'b00000, 7'b0010011};


				// primitive instructions
//				0:		DI = {20'b0000_0000_0000_0000_0001, 5'b00001, 7'b0110111};
//				1:		DI = {12'b0000_0000_1000, 5'b00001, 3'b010, 5'b00010, 7'b0000011};
//				2:		DI = {12'b0000_0000_1001, 5'b00001, 3'b010, 5'b00011, 7'b0000011};
//				3:		DI = {7'b0000000, 5'b00010, 5'b00011, 3'b000, 5'b00100, 7'b0110011};
//				4:		DI = {7'b0000000, 5'b00100, 5'b00001, 3'b010, 5'b10000, 7'b0100011};
//				5:		DI = {12'b0000_0100_0000, 5'b00000, 3'b000, 5'b00001, 7'b0010011};
//				6:		DI = {7'b0000001, 5'b00001, 5'b00000, 3'b100, 5'b00010, 7'b0110011};


				default:	DI = 32'd0;
			endcase
		end


		// 2'b10 : data
		for (i = 0; i < 32768; i = i+1) begin
			#(`PER)
			ADDR	=	2'b10;
			WEN	=	1'b0;
			DI	=	i << 10;
		end

		#(`PER)
		ADDR	=	2'b00;
		WEN	=	1'b0;
		DI	=	{31'd0, 1'b1};

		#(`PER)
		ADDR	=	2'b00;
		WEN	=	1'b1;

		i	=	0;
		while(~end_flag) begin
			#(`PER)
			i	= i+1;
		end

		#(`PER)
		ADDR	=	2'b00;
		WEN	=	1'b0;
		DI	=	{31'd0, 1'b0};

		#(`PER)
		ADDR	=	2'b11;
		WEN	=	1'b1;
	
		#(1000*`PER)
	
		$stop;
	end
	
	always begin
		#(`PER/2)
		CLK	=	~CLK;
	
		#(`PER/2)
		CLK	=	~CLK;
	end
	

endmodule
